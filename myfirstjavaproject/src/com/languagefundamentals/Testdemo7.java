package com.languagefundamentals;

public class Testdemo7 {
	
//Literals : the constant values which are stored in variable 
//literals :
//1.integral literal 
//2.floating literal 
//3.Character literal 
//4.boolean literal 

	
	public static void main(String[] args) {
//1.Integral Literal 
//decimal - (0-9) -- start with number not with 0
		
		int v = 12349874;
		
//2.octa - (0-7) -- start with Zero 
		int v1 = 01234;

//3.hexadecimal - start with zero -- (0-9) and (a-f) here a = 10,b = 11, c = 12,d = 13, e = 14,f = 15
		int v2 = 0xbcd234;
		
//4.binary - 0 and 1 
		int v3 = 0b1101;
		int v4 = 07 ;
		
		System.out.println(v);
		System.out.println(v1);
		System.out.println(v2);
		System.out.println(v3);
		System.out.println(v4);

	}

}
